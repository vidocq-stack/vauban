package io.vidocq.vauban.processor.apt.repeatable;

import java.lang.annotation.ElementType;
import java.lang.annotation.Repeatable;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;

/**
 * A repeatable annotation of the processor path for type uses: written twice on a type, the compiler wraps it in
 * {@link List} (BUG-20261117-56).
 */
@Repeatable(Mark.List.class)
@Retention(RetentionPolicy.RUNTIME)
@Target(ElementType.TYPE_USE)
public @interface Mark {

    String value();

    /** The container of {@link Mark}. */
    @Retention(RetentionPolicy.RUNTIME)
    @Target(ElementType.TYPE_USE)
    public @interface List {
        Mark[] value();
    }
}
