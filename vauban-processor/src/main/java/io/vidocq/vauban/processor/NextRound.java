package io.vidocq.vauban.processor;

import javax.annotation.processing.Filer;
import javax.annotation.processing.FilerException;
import javax.annotation.processing.Messager;
import javax.lang.model.element.TypeElement;
import javax.tools.Diagnostic;
import java.io.IOException;

/**
 * Asks javac for one more annotation processing round (BUG-20261115-06).
 *
 * <p>javac starts a round only for the source and class files the previous one created: in a module whose only
 * processor is Vauban, as foy-cdi-vauban, the round after the first is the last, and each class written there costs
 * a "created in the last round will not be subject to annotation processing" warning. A round in which Vauban waits
 * for the other processors writes a compilation unit that declares no type, so that the next round is not the last:
 * Vauban writes its classes there. The unit compiles to nothing; only its source stays, beside Vauban's other
 * generated sources.</p>
 */
final class NextRound {

    /** The name of the unit each such round writes, followed by the round's number. */
    static final String UNIT_PREFIX = "_VaubanRound";

    private NextRound() {
    }

    /**
     * Writes, in package {@code pkg}, that of {@code origin}, a compilation unit without types for round
     * {@code round}. When the Filer refuses its name, Vauban writes its classes in the last round, as before; when
     * the unit cannot be written for another reason, a note says so first.
     */
    static void request(Filer filer, Messager messager, String pkg, TypeElement origin, int round) {
        var name = pkg.isEmpty() ? UNIT_PREFIX + round : pkg + "." + UNIT_PREFIX + round;
        try (var writer = filer.createSourceFile(name, origin).openWriter()) {
            writer.write("""
                    // Generated by Vauban's annotation processor. It declares no type: javac gives it one more
                    // annotation processing round, where Vauban writes its classes instead of the last round.
                    """);
            if (!pkg.isEmpty()) {
                writer.write("package " + pkg + ";\n");
            }
        } catch (FilerException _) {
            // The Filer refused the name, which a source of the compilation declares: the classes are written in the
            // last round, with javac's warning each, which is all this unit saves.
        } catch (IOException e) {
            messager.printMessage(Diagnostic.Kind.NOTE, "[Vauban] Could not write " + name + " (" + e
                    + "), which asks javac for one more round: Vauban writes its classes in javac's last round.");
        }
    }
}
