package io.vidocq.vauban.core.container;

import io.vidocq.vauban.core.container.RuntimeGeneration.Generated;
import io.vidocq.vauban.core.container.RuntimeGeneration.Kind;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.enterprise.context.Dependent;
import jakarta.enterprise.context.RequestScoped;
import jakarta.enterprise.inject.Produces;
import jakarta.inject.Inject;
import jakarta.interceptor.AroundInvoke;
import jakarta.interceptor.Interceptor;
import jakarta.interceptor.InterceptorBinding;
import jakarta.interceptor.InvocationContext;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The classes a container generates at run time are announced loudly (vauban#227): this module's tests are compiled
 * without the annotation processor, so every intercepted subclass and client proxy here is generated by the container.
 */
@DisplayName("RuntimeGeneration - classes generated at run time are announced at boot")
class RuntimeGenerationTest {

    @InterceptorBinding
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.TYPE, ElementType.METHOD})
    public @interface Logged {}

    @Logged
    @Interceptor
    @Priority(1)
    public static class LoggedInterceptor {
        @AroundInvoke
        Object around(InvocationContext context) throws Exception {
            return context.proceed();
        }
    }

    @Dependent
    public static class Audited {
        @Logged
        public String run() {
            return "ran";
        }
    }

    public interface Identity {
        String name();
    }

    @ApplicationScoped
    public static class IdentityProducer {
        @Produces
        @RequestScoped
        public Identity currentIdentity() {
            return () -> "alice";
        }
    }

    @ApplicationScoped
    public static class Greeter {
        @Inject
        Identity identity;

        public String greet() {
            return "hello";
        }
    }

    @Test
    @DisplayName("the boot lists the subclasses it generated and the proxies no build output supplies")
    void bootListsWhatItGenerates() {
        try (var container = VaubanContainer.builder()
                .addBeanClass(Audited.class)
                .addBeanClass(LoggedInterceptor.class)
                .addBeanClass(IdentityProducer.class)
                .addBeanClass(Greeter.class)
                .build()) {
            var generation = container.runtimeGeneration();
            var atBoot = generation.recordedAtBoot();

            assertTrue(atBoot.contains(new Generated(Kind.INTERCEPTED_SUBCLASS, Audited.class.getName() + "$$Intercepted")),
                    String.valueOf(atBoot));
            assertTrue(atBoot.contains(new Generated(Kind.CLIENT_PROXY, Greeter.class.getName() + "_ClientProxy")),
                    String.valueOf(atBoot));
            assertTrue(atBoot.contains(new Generated(Kind.CLIENT_PROXY, IdentityProducer.class.getName() + "_ClientProxy")),
                    String.valueOf(atBoot));
            assertTrue(atBoot.contains(new Generated(Kind.INTERFACE_PROXY, Identity.class.getName())),
                    String.valueOf(atBoot));
            assertEquals(Set.copyOf(atBoot), generation.announced(), "the boot announced them all");

            // The predicted proxies are created now: the boot announced them, so nothing more is announced.
            assertEquals("hello", container.select(Greeter.class).greet());
            assertEquals("ran", container.select(Audited.class).run());
            assertEquals(Set.copyOf(atBoot), generation.announced());
        }
    }

    @Test
    @DisplayName("the boot warning names each class and how to generate it at build time")
    void bootWarning() {
        var warnings = new ArrayList<String>();
        var generation = new RuntimeGeneration(warnings::add);
        generation.record(Kind.INTERCEPTED_SUBCLASS, "app.Audited$$Intercepted");
        generation.record(Kind.CLIENT_PROXY, "app.Greeter_ClientProxy");
        assertEquals(List.of(), warnings, "nothing before the end of the boot");

        generation.bootCompleted();

        assertEquals(1, warnings.size(), String.valueOf(warnings));
        var warning = warnings.getFirst();
        assertTrue(warning.contains("VAUBAN — RUNTIME CODE GENERATION FALLBACK"), warning);
        assertTrue(warning.contains("2 classes are generated at boot instead of at build time:\n"
                + "  - intercepted subclass app.Audited$$Intercepted\n"
                + "  - client proxy app.Greeter_ClientProxy\n"), warning);
        assertTrue(warning.contains("add vauban-processor to the annotation processor path"), warning);
    }

    @Test
    @DisplayName("after the boot, a class the boot did not announce is announced once, alone")
    void afterTheBootEachNewClassOnce() {
        var warnings = new ArrayList<String>();
        var generation = new RuntimeGeneration(warnings::add);
        generation.record(Kind.CLIENT_PROXY, "app.Early_ClientProxy");
        generation.bootCompleted();
        assertEquals(1, warnings.size(), String.valueOf(warnings));

        generation.record(Kind.CLIENT_PROXY, "app.Early_ClientProxy");
        generation.record(Kind.CLIENT_PROXY, "app.Late_ClientProxy");
        generation.record(Kind.CLIENT_PROXY, "app.Late_ClientProxy");

        assertEquals(2, warnings.size(), String.valueOf(warnings));
        var late = warnings.getLast();
        assertTrue(late.contains("1 class is generated now, after the boot instead of at build time:\n"
                + "  - client proxy app.Late_ClientProxy\n"), late);
        assertEquals(List.of(new Generated(Kind.CLIENT_PROXY, "app.Early_ClientProxy")), generation.recordedAtBoot());
    }

    @Test
    @DisplayName("a boot that generates nothing says nothing")
    void nothingGeneratedNothingSaid() {
        var warnings = new ArrayList<String>();
        new RuntimeGeneration(warnings::add).bootCompleted();
        assertEquals(List.of(), warnings);
    }
}
