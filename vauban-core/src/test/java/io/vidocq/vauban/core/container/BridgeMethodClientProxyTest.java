package io.vidocq.vauban.core.container;

import io.vidocq.vauban.core.codegen.ClassTypeView;
import io.vidocq.vauban.core.codegen.TypeView;
import io.vidocq.vauban.core.container.RuntimeGeneration.Generated;
import io.vidocq.vauban.core.container.RuntimeGeneration.Kind;
import io.vidocq.vauban.core.proxy.RuntimeClientProxyGenerator;
import jakarta.annotation.PostConstruct;
import jakarta.annotation.Priority;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import jakarta.interceptor.AroundInvoke;
import jakarta.interceptor.Interceptor;
import jakarta.interceptor.InterceptorBinding;
import jakarta.interceptor.InvocationContext;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.lang.annotation.ElementType;
import java.lang.annotation.Retention;
import java.lang.annotation.RetentionPolicy;
import java.lang.annotation.Target;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;
import java.util.function.Supplier;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * A client proxy the container generates at run time forwards a method the compiler gave a bridge (BUG-20261117-49):
 * {@code String get()} of a {@code Supplier<String>}, next to the bridge {@code Object get()}, and a covariant
 * override, next to the bridge with the overridden return type. A call through the bean's reference reaches the
 * interceptor and the contextual instance, whether the caller types it by the bean or by the supertype. This module's
 * tests are compiled without the annotation processor: every proxy here is generated by the container, which each
 * test checks.
 */
@DisplayName("Run-time client proxy - a method with a compiler bridge reaches the interceptor and the instance")
class BridgeMethodClientProxyTest {

    private static final String INSTANCE = "instance";

    @InterceptorBinding
    @Retention(RetentionPolicy.RUNTIME)
    @Target({ElementType.TYPE, ElementType.METHOD})
    public @interface Traced {}

    /** The calls the interceptor saw. */
    @ApplicationScoped
    public static class Trace {
        private final List<String> calls = new CopyOnWriteArrayList<>();

        public void add(String call) {
            calls.add(call);
        }

        public List<String> calls() {
            return List.copyOf(calls);
        }
    }

    @Traced
    @Interceptor
    @Priority(1)
    public static class TracedInterceptor {
        @Inject
        Trace trace;

        @AroundInvoke
        Object around(InvocationContext context) throws Exception {
            trace.add(context.getMethod().getName());
            return context.proceed();
        }
    }

    /**
     * Implements {@code Supplier<String>}: javac adds the bridge {@code Object get()}. The state is set on the
     * contextual instance only: a call that runs on the proxy reads {@code null}.
     */
    @Traced
    @ApplicationScoped
    public static class OwnSupplier implements Supplier<String> {
        private String state;

        @PostConstruct
        void init() {
            state = INSTANCE;
        }

        @Override
        public String get() {
            return state;
        }
    }

    /** Declares {@code get()} and its bridge; its subclass declares neither. */
    public static class SupplierBase implements Supplier<String> {
        private String state;

        @PostConstruct
        void init() {
            state = INSTANCE;
        }

        @Override
        public String get() {
            return state;
        }
    }

    @Traced
    @ApplicationScoped
    public static class InheritedSupplier extends SupplierBase {
    }

    /**
     * Not public, and declares {@code get()}: javac gives a public subclass a bridge {@code String get()} of its own,
     * which calls this one.
     */
    static class HiddenSupplierBase extends SupplierBase {
        @Override
        public String get() {
            return super.get();
        }
    }

    /** Its {@code get()} is a bridge to {@code HiddenSupplierBase.get()}, which is intercepted (BUG-20261118-16). */
    @Traced
    @ApplicationScoped
    public static class VisiblyInheritedSupplier extends HiddenSupplierBase {
    }

    public static class NamedBase {
        public CharSequence name() {
            return "base";
        }
    }

    /** A covariant override: javac adds the bridge {@code CharSequence name()}. */
    @Traced
    @ApplicationScoped
    public static class CovariantName extends NamedBase {
        private String state;

        @PostConstruct
        void init() {
            state = INSTANCE;
        }

        @Override
        public String name() {
            return state;
        }
    }

    public static class NumberBase {
        public Number value() {
            return 0;
        }
    }

    /** A covariant override too, whose bridge is {@code Number value()}. */
    @Traced
    @ApplicationScoped
    public static class CovariantValue extends NumberBase {
        private Integer state;

        @PostConstruct
        void init() {
            state = 42;
        }

        @Override
        public Integer value() {
            return state;
        }
    }

    @Test
    @DisplayName("the bean's own get(), next to the bridge javac adds for Supplier<String>")
    void ownGet() {
        try (var container = start(OwnSupplier.class)) {
            var bean = container.select(OwnSupplier.class);
            assertReachesTheInstance(container, OwnSupplier.class, "get", INSTANCE, bean::get,
                    ((Supplier<?>) bean)::get);
        }
    }

    @Test
    @DisplayName("get() inherited from a superclass that implements Supplier<String>")
    void inheritedGet() {
        try (var container = start(InheritedSupplier.class)) {
            var bean = container.select(InheritedSupplier.class);
            assertReachesTheInstance(container, InheritedSupplier.class, "get", INSTANCE, bean::get,
                    ((Supplier<?>) bean)::get);
        }
    }

    @Test
    @DisplayName("get() inherited through a superclass that is not public, which gives the bean a bridge of its own")
    void getInheritedThroughAHiddenSuperclass() {
        try (var container = start(VisiblyInheritedSupplier.class)) {
            var bean = container.select(VisiblyInheritedSupplier.class);
            assertReachesTheInstance(container, VisiblyInheritedSupplier.class, "get", INSTANCE, bean::get,
                    ((Supplier<?>) bean)::get);
        }
    }

    @Test
    @DisplayName("a covariant override String name() of CharSequence name()")
    void covariantName() {
        try (var container = start(CovariantName.class)) {
            var bean = container.select(CovariantName.class);
            assertReachesTheInstance(container, CovariantName.class, "name", INSTANCE, bean::name,
                    ((NamedBase) bean)::name);
        }
    }

    @Test
    @DisplayName("a covariant override Integer value() of Number value()")
    void covariantValue() {
        try (var container = start(CovariantValue.class)) {
            var bean = container.select(CovariantValue.class);
            assertReachesTheInstance(container, CovariantValue.class, "value", 42, bean::value,
                    ((NumberBase) bean)::value);
        }
    }

    private static VaubanContainer start(Class<?> bean) {
        return VaubanContainer.builder()
                .addBeanClass(Trace.class)
                .addBeanClass(TracedInterceptor.class)
                .addBeanClass(bean)
                .build();
    }

    /**
     * Calls {@code method} twice, typed by the bean, then by the supertype it overrides: both reach the contextual
     * instance, and the interceptor when the bean is {@code @Traced}, through a client proxy the container generated.
     */
    private static void assertReachesTheInstance(VaubanContainer container, Class<?> bean, String method,
            Object expected, Supplier<?> typedByTheBean, Supplier<?> typedByTheSupertype) {
        var diagnosis = diagnosis(bean, method);
        var intercepted = bean.isAnnotationPresent(Traced.class) ? List.of(method, method) : List.<String>of();
        assertAll(
                () -> assertEquals(expected, typedByTheBean.get(), "typed by the bean: " + diagnosis),
                () -> assertEquals(expected, typedByTheSupertype.get(), "typed by the supertype: " + diagnosis),
                () -> assertEquals(intercepted, container.select(Trace.class).calls(),
                        "the calls the interceptor saw: " + diagnosis));
        var proxy = new Generated(Kind.CLIENT_PROXY, RuntimeClientProxyGenerator.proxyClassName(bean));
        assertTrue(container.runtimeGeneration().announced().contains(proxy),
                () -> "the container did not generate " + proxy.className() + " at run time: "
                        + container.runtimeGeneration().announced());
    }

    /**
     * The declarations of {@code method} the run-time walk meets, in its order, bridges marked, and the methods the
     * proxy forwards: names the method a proxy leaves out, and the declaration that took its place.
     */
    private static String diagnosis(Class<?> bean, String method) {
        var met = new ArrayList<String>();
        for (TypeView c = ClassTypeView.of(bean); c != null; c = c.superclass()) {
            for (var m : c.methods()) {
                if (m.name().equals(method)) {
                    met.add((m.isBridge() ? "bridge " : "") + m.returnType() + " "
                            + ((ClassTypeView) c).type().getSimpleName() + "." + method + "()");
                }
            }
        }
        var forwarded = RuntimeClientProxyGenerator.shapeOf(bean).methods().stream()
                .map(m -> m.returnType() + " " + m.name() + "()").toList();
        return "the run-time walk meets " + met + ", the proxy " + RuntimeClientProxyGenerator.proxyClassName(bean)
                + " forwards " + forwarded;
    }
}
